CREATE TABLE education.departments (
  department_id integer PRIMARY KEY,
  name text NOT NULL UNIQUE
);

CREATE TABLE education.employees (
  employee_id integer PRIMARY KEY,
  name text NOT NULL,
  department_id integer REFERENCES education.departments(department_id),
  manager_id integer REFERENCES education.employees(employee_id),
  hired_at date NOT NULL,
  salary numeric(10, 2) NOT NULL CHECK (salary > 0)
);

CREATE TABLE education.customers (
  customer_id integer PRIMARY KEY,
  name text NOT NULL,
  email text,
  city text NOT NULL,
  created_at date NOT NULL
);

CREATE TABLE education.categories (
  category_id integer PRIMARY KEY,
  name text NOT NULL UNIQUE
);

CREATE TABLE education.products (
  product_id integer PRIMARY KEY,
  category_id integer REFERENCES education.categories(category_id),
  name text NOT NULL,
  unit_price numeric(10, 2) NOT NULL CHECK (unit_price >= 0),
  stock_quantity integer NOT NULL CHECK (stock_quantity >= 0),
  discontinued_at date
);

CREATE TABLE education.orders (
  order_id integer PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES education.customers(customer_id),
  employee_id integer REFERENCES education.employees(employee_id),
  ordered_at timestamptz NOT NULL,
  shipped_at timestamptz,
  status text NOT NULL CHECK (status IN ('pending', 'completed', 'cancelled'))
);

CREATE TABLE education.order_items (
  order_id integer NOT NULL REFERENCES education.orders(order_id),
  product_id integer NOT NULL REFERENCES education.products(product_id),
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(10, 2) NOT NULL CHECK (unit_price >= 0),
  discount_percent numeric(5, 2) CHECK (discount_percent BETWEEN 0 AND 100),
  PRIMARY KEY (order_id, product_id)
);

